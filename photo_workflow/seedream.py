class SeedreamError(RuntimeError):
    """An edit failed; the caller must not report this photograph as completed."""

    def __init__(self, message, *, code=None, status=None, request_id=None, diagnostic=None):
        super().__init__(message)
        self.code, self.status, self.request_id = code, status, request_id
        self.diagnostic = diagnostic or {}


def make_prompt(style="folders", profile=None):
    if style not in STYLE_BRIEFS:
        raise SeedreamError("未知的后期风格。")
    if profile is not None and profile not in PROFILES:
        raise SeedreamError("未知的文件夹后期策略。")
    parts = [PRESERVATION_PROMPT, STYLE_BRIEFS[style]]
    if style == "folders" and profile in PROFILES:
        parts.append("本张照片的后期目标：" + PROFILES[profile]["brief"])
    return "\n".join(parts)


def _validate_size(size):
    if not isinstance(size, str):
        raise SeedreamError("输出尺寸应为 1K、1.5K、2K 或宽x高像素。")
    if size in {"1K", "1.5K", "2K"}:
        return size
    match = re.fullmatch(r"([1-9][0-9]*)x([1-9][0-9]*)", size)
    if not match:
        raise SeedreamError("Seedream 5.0 Pro 仅支持 1K、1.5K、2K；不支持 4K。也可填写有效的宽x高像素。")
    try:
        width, height = (int(part) for part in match.groups())
    except ValueError:
        raise SeedreamError("输出尺寸不是有效的宽x高像素。") from None
    if not 921600 <= width * height <= 4624220 or not 1 / 16 <= width / height <= 16:
        raise SeedreamError("Seedream 5.0 Pro 自定义尺寸总像素必须在 921600–4624220 之间，宽高比在 1/16–16 之间。")
    return size


def _image_info(content, *, input_image=False):
    try:
        with Image.open(io.BytesIO(content)) as image:
            image_format = image.format
            width, height = image.size
            # Reject oversized headers before allocating their decoded pixels.
            maximum_pixels = 36_000_000 if input_image else 4_624_220
            if width * height > maximum_pixels:
                raise SeedreamError("图片总像素超出 Seedream 5.0 Pro 的输入或输出限制，未处理照片。")
            image.verify()
        # Force pixel decoding as verify() alone does not detect all broken JPEGs.
        with Image.open(io.BytesIO(content)) as image:
            image.load()
    except (OSError, ValueError, SyntaxError, Image.DecompressionBombError):
        label = "输入图片" if input_image else "Seedream 返回的图片"
        raise SeedreamError(label + "损坏或不是有效的图片，未保存为完成结果。") from None
    if image_format != "JPEG":
        message = "输入图片必须为 JPEG 格式。" if input_image else "接口要求返回 JPEG，但实际图片并非 JPEG，未保存结果。"
        raise SeedreamError(message)
    return width, height


def _safe_identifier(value, api_key):
    if not isinstance(value, str):
        return None
    value = redact(value, api_key)
    return value if re.fullmatch(r"[A-Za-z0-9_.:-]{1,200}", value) else None


def _safe_usage(value):
    # Only numeric usage counters belong in the audit. Never store returned URLs,
    # request bodies, headers, or arbitrary strings in a manifest.
    if not isinstance(value, dict):
        return {}
    return {
        name: number for name, number in value.items()
        if isinstance(name, str) and re.fullmatch(r"[a-z_]{1,60}", name)
        and not isinstance(number, bool) and isinstance(number, (int, float))
        and (isinstance(number, int) or math.isfinite(number)) and number >= 0
    }


def _service_error(error, api_key, status=None, request_id=None):
    code = _safe_identifier(error.get("code"), api_key) if isinstance(error, dict) else None
    code = code or "SeedreamGenerationFailed"
    if code == "ModelNotOpen":
        hint = "当前账号尚未开通 Seedream 5.0 Pro，请在火山方舟控制台的开通管理页开通该模型服务。"
    elif "ModelIDAccessDisabled" in code:
        hint = "当前账号不允许通过 Model ID 调用；请在火山方舟检查该账号的模型调用权限。此工作流固定使用指定的 Seedream 5.0 Pro。"
    else:
        hint = {
            400: "图片编辑请求被拒绝，请检查 Seedream 5.0 Pro 的输入图片和输出尺寸。该模型应调用 images/generations 图片接口。",
            401: "API Key 无效或已失效，请重新配置。",
            403: "没有 Seedream 5.0 Pro 的调用权限，请检查账号权限与模型开通状态。",
            404: "指定的 Seedream 5.0 Pro 模型不存在或尚未开通。请检查模型 ID 与开通管理；该模型属于 images/generations 图片接口。",
            429: "图片生成频率或额度受限，请检查账户余额及限流配置后重试。",
        }.get(status, "Seedream 未成功返回图片，未将此照片报告为完成。为避免重复收费，没有自动重发。")
    prefix = f"HTTP {status} " if status else ""
    return SeedreamError(redact(prefix + code + "：" + hint, api_key), code=code, status=status, request_id=_safe_identifier(request_id, api_key))


def _header_value(headers, name):
    if headers is None:
        return None
    return headers.get(name) or headers.get(name.lower())


def _retry_delay(headers, attempt):
    """Use exponential backoff and either RFC 9110 Retry-After representation."""
    requested_delay = 0.0
    retry_after = _header_value(headers, "Retry-After")
    if isinstance(retry_after, str):
        value = retry_after.strip()
        try:
            if re.fullmatch(r"[0-9]+", value):
                requested_delay = min(60.0, float(value))
            else:
                deadline = parsedate_to_datetime(value)
                if deadline.tzinfo is None:
                    deadline = deadline.replace(tzinfo=timezone.utc)
                requested_delay = max(0.0, min(60.0, deadline.timestamp() - time.time()))
        except (ValueError, TypeError, OverflowError):
            pass  # Invalid server hints use the normal local backoff.
    backoff = 3.0 * (2 ** attempt)
    return min(60.0, max(backoff, requested_delay) + random.uniform(0.0, 0.5))


def _check_cancel(stop_event):
    if stop_event is not None and stop_event.is_set():
        raise SeedreamError("任务已取消，未发起新的 Seedream 请求。", code="Cancelled")


def _wait_for_retry(delay, stop_event):
    _check_cancel(stop_event)
    if stop_event is None:
        time.sleep(delay)
    elif stop_event.wait(delay):
        raise SeedreamError("已取消限流等待，未发起新的 Seedream 请求。", code="Cancelled")


def _private_write(path, content):
    """Private response checkpoints are never served by the workbench."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
    fd, temporary = tempfile.mkstemp(prefix=".response-", dir=path.parent)
    try:
        os.fchmod(fd, 0o600)
        with os.fdopen(fd, "wb") as stream:
            stream.write(content)
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def _response_metadata(response, api_key):
    headers = getattr(response, "headers", {})
    content_type = _header_value(headers, "Content-Type") or "unknown"
    encoding = _header_value(headers, "Content-Encoding") or "identity"
    # Header values must not become an arbitrary string channel into manifests.
    content_type = content_type.split(";", 1)[0].strip().lower()
    content_type = content_type if re.fullmatch(r"[a-z0-9.+/-]{1,100}", content_type) else "unknown"
    encoding = encoding.strip().lower()
    encoding = encoding if encoding in {"identity", "gzip", "deflate"} else "unsupported"
    status = getattr(response, "status", 200)
    return {
        "http_status": status if isinstance(status, int) else 200,
        "content_type": content_type,
        "content_encoding": encoding,
        "request_id": _safe_identifier(_header_value(headers, "X-Request-Id") or _header_value(headers, "X-Tt-Logid"), api_key),
    }


def _decode_response(raw, metadata):
    if len(raw) > MAX_RESPONSE_BYTES:
        raise SeedreamError("Seedream 响应超过大小限制，未保存成片；没有自动重新生成。", code="ResponseTooLarge")
    encoding = metadata.get("body_encoding", metadata.get("content_encoding", "identity"))
    if encoding == "identity":
        return raw
    if encoding not in {"gzip", "deflate"}:
        raise SeedreamError("Seedream 返回了不支持的响应压缩格式；没有自动重新生成。", code="UnsupportedResponseEncoding")
    try:
        decoder = zlib.decompressobj(16 + zlib.MAX_WBITS if encoding == "gzip" else zlib.MAX_WBITS)
        decoded = decoder.decompress(raw, MAX_RESPONSE_BYTES + 1)
        if len(decoded) > MAX_RESPONSE_BYTES or decoder.unconsumed_tail:
            raise SeedreamError("Seedream 解压后的响应超过大小限制；没有自动重新生成。", code="ResponseTooLarge")
        if not decoder.eof:
            raise SeedreamError("Seedream 的压缩响应不完整；没有自动重新生成。", code="ResponseIncomplete")
        return decoded
    except zlib.error:
        raise SeedreamError("Seedream 的压缩响应无法解码；没有自动重新生成。", code="ResponseCompressionError") from None


def _download_image(url, context, request_id, on_retry):
    """Retry this existing result's GET only; never resend generation here."""
    try:
        parsed = urlsplit(url)
        valid = parsed.scheme == "https" and bool(parsed.hostname) and not parsed.username and not parsed.password and parsed.port in {None, 443}
        valid = valid and parsed.hostname not in {"localhost", "localhost.localdomain"} and "." in parsed.hostname and not parsed.hostname.endswith(".local")
        try:
            valid = valid and ipaddress.ip_address(parsed.hostname).is_global
        except ValueError:
            pass
    except (ValueError, AttributeError):
        valid = False
    if not valid:
        raise SeedreamError("Seedream 返回了无效的图片下载地址，未重新生成。", code="InvalidResultURL", request_id=request_id)
    request = urllib.request.Request(url, headers={"Accept": "image/jpeg", "Accept-Encoding": "identity"}, method="GET")
    for attempt in range(3):
        try:
            # This request deliberately contains no API credential.
            with urllib.request.urlopen(request, timeout=90, context=context) as response:
                content = response.read(MAX_RESPONSE_BYTES + 1)
            _image_info(content)
            return content
        except (urllib.error.URLError, TimeoutError, OSError, http.client.HTTPException, SeedreamError) as exc:
            status = exc.code if isinstance(exc, urllib.error.HTTPError) else None
            if isinstance(exc, urllib.error.HTTPError):
                exc.close()
            if attempt < 2 and status not in {400, 401, 403, 404, 410}:
                if on_retry:
                    on_retry(f"生成结果下载失败，重试下载（第 {attempt + 2}/3 次）；不会重新生成图片。")
                time.sleep(1.0 * (2 ** attempt))
                continue
            hint = "下载链接拒绝访问或已失效" if status in {403, 404, 410} else "生成结果下载失败"
            raise SeedreamError(hint + "；已保留接口响应，再次运行只尝试下载已有结果，不会自动重新生成。", code="ResultDownloadFailed", status=status, request_id=request_id, diagnostic={"stage": "download", "exception_type": type(exc).__name__}) from None


def _parse_response(raw, metadata, api_key, size, context, on_retry):
    request_id = metadata.get("request_id")
    diagnostic = {k: v for k, v in metadata.items() if k in {"http_status", "content_type", "content_encoding", "response_bytes"}}
    diagnostic["stage"] = "response_decode"
    try:
        decoded = _decode_response(raw, metadata)
        diagnostic["stage"] = "json_parse"
        try:
            data = json.loads(decoded.decode("utf-8-sig"))
        except (json.JSONDecodeError, UnicodeDecodeError) as exc:
            diagnostic["exception_type"] = type(exc).__name__
            if isinstance(exc, json.JSONDecodeError):
                diagnostic.update(json_line=exc.lineno, json_column=exc.colno, json_position=exc.pos)
            description = "空响应" if not decoded.strip() else "非 JSON 或不完整的 JSON 响应"
            raise SeedreamError(f"Seedream 返回{description}（HTTP {metadata.get('http_status', 200)}，{diagnostic.get('content_type', 'unknown')}）；已保存本地诊断，没有自动重新生成。", code="ResponseJSONInvalid", diagnostic=diagnostic) from None
        diagnostic["stage"] = "response_schema"
        if not isinstance(data, dict):
            raise SeedreamError("Seedream 返回了无法识别的响应结构，未保存成片。", code="ResponseSchemaInvalid")
        request_id = request_id or _safe_identifier(data.get("request_id") or data.get("id"), api_key)
        if data.get("error"):
            raise _service_error(data["error"], api_key, request_id=request_id)
        items = data.get("data")
        if not isinstance(items, list) or len(items) != 1 or not isinstance(items[0], dict):
            raise SeedreamError("Seedream 未返回预期的单张后期照片，未保存成片。", code="ResponseSchemaInvalid")
        item = items[0]
        if item.get("error"):
            raise _service_error(item["error"], api_key, request_id=request_id)
        encoded, url = item.get("b64_json"), item.get("url")
        if isinstance(encoded, str) and encoded.strip():
            diagnostic["stage"] = "base64_decode"
            try:
                content = base64.b64decode(encoded.strip(), validate=True)
            except (binascii.Error, ValueError):
                raise SeedreamError("Seedream 返回的图片 Base64 无效，未保存成片。", code="ResponseBase64Invalid") from None
            response_format = "b64_json"
        elif isinstance(url, str) and url:
            diagnostic["stage"] = "download"
            content = _download_image(url, context, request_id, on_retry)
            response_format = "url"
        else:
            raise SeedreamError("Seedream 未返回图片数据或下载地址，未保存成片。", code="ResponseImageMissing")
        diagnostic["stage"] = "image_validate"
        width, height = _image_info(content)
        if item.get("output_format", "jpeg") != "jpeg":
            raise SeedreamError("Seedream 返回的格式与请求的 JPEG 不符，未保存成片。", code="ResponseImageFormatInvalid")
        return content, {
            "request_id": request_id, "model": MODEL, "usage": _safe_usage(data.get("usage")),
            "requested_size": size, "size": f"{width}x{height}", "output_format": "jpeg",
            "response_format": response_format, "watermark": False,
        }
    except SeedreamError as exc:
        exc.request_id = exc.request_id or request_id
        exc.diagnostic = {**diagnostic, **exc.diagnostic}
        exc.code = exc.code or "ResponseImageInvalid"
        # A HTTP 200 body does not become an HTTP error merely because JSON broke.
        if exc.status is None and metadata.get("http_status"):
            exc.status = metadata["http_status"]
        raise
    except (ValueError, TypeError, AttributeError) as exc:
        diagnostic["exception_type"] = type(exc).__name__
        raise SeedreamError("Seedream 响应处理失败，已记录具体阶段；没有自动重新生成。", code="ResponseProcessingError", status=metadata.get("http_status"), request_id=request_id, diagnostic=diagnostic) from None


def edit(image_bytes, config, prompt, size="2K", *, request_gate=None, on_retry=None, stop_event=None, response_dir=None, request_identity=None):
    """Generate once, checkpoint the response, then download the existing result.

    Only explicit HTTP 429 can retry the POST. GET download retries incur no
    new generation. A saved response is always recovered before considering a
    new POST, including malformed responses whose billing outcome is unknown.
    """
    _check_cancel(stop_event)
    try:
        api_key = validate_api_key(config.get("api_key"))
    except ValueError as exc:
        raise SeedreamError(str(exc), code="InvalidAPIKeyFormat", diagnostic={"stage": "configuration"}) from None
    if config.get("model") != MODEL:
        raise SeedreamError("此图片编辑工作流必须使用模型 " + MODEL + "，不能使用视觉理解模型或 Chat 接口模型。")
    if not isinstance(prompt, str) or not prompt.strip():
        raise SeedreamError("图片后期提示词不能为空。")
    size = _validate_size(size)
    if not isinstance(image_bytes, (bytes, bytearray)) or not image_bytes:
        raise SeedreamError("没有可上传的 JPEG 图片。")
    if len(image_bytes) > MAX_INPUT_BYTES:
        raise SeedreamError("输入图片超过 Seedream 的 30 MB 单图限制，请先缩小图片。")
    width, height = _image_info(image_bytes, input_image=True)
    if width <= 14 or height <= 14 or not 1 / 16 <= width / height <= 16:
        raise SeedreamError("输入图片必须满足宽高大于 14 像素、总像素不超过 3600 万、宽高比在 1/16–16 之间。")
    try:
        import certifi
        context = ssl.create_default_context(cafile=certifi.where())
    except ImportError:
        context = ssl.create_default_context()
    saved_body = Path(response_dir) / "response.bin" if response_dir else None
    saved_meta = Path(response_dir) / "response-meta.json" if response_dir else None
    # The pipeline's identity contains the original SHA and preprocessing version.
    # Regenerated JPEGs may differ only in an ICC creation timestamp after restart.
    if request_identity is None:
        with Image.open(io.BytesIO(image_bytes)) as image:
            request_identity = [image.mode, image.size, hashlib.sha256(image.tobytes()).hexdigest()]
    fingerprint = hashlib.sha256(json.dumps([MODEL, prompt, size, request_identity], ensure_ascii=False).encode()).hexdigest()
    if saved_meta and saved_meta.exists():
        metadata = json.loads(saved_meta.read_text(encoding="utf-8"))
        if metadata.get("request_fingerprint") != fingerprint:
            raise SeedreamError("已保存响应与当前请求不符；未重新生成，请检查本地缓存。", code="ResponseCheckpointMismatch")
        if not metadata.get("complete") or not saved_body.exists():
            raise SeedreamError("上次请求未收到完整响应，生成状态未知；为避免重复收费，没有自动重发。请用 Request ID 查询服务端记录。", code="GenerationOutcomeUnknown", request_id=metadata.get("request_id"), diagnostic={"stage": "response_read", "response_bytes": metadata.get("response_bytes", 0)})
        raw = saved_body.read_bytes()
        content, audit = _parse_response(raw, metadata, api_key, size, context, on_retry)
        audit["recovered_response"] = True
        return content, audit
    payload = {
        "model": MODEL, "prompt": prompt,
        "image": "data:image/jpeg;base64," + base64.b64encode(image_bytes).decode("ascii"),
        "size": size, "output_format": "jpeg", "response_format": "url", "watermark": False,
    }
    request = urllib.request.Request(API_URL, data=json.dumps(payload, ensure_ascii=False).encode("utf-8"), headers={
        "Authorization": "Bearer " + api_key, "Content-Type": "application/json", "Accept-Encoding": "identity",
    }, method="POST")
    # Persist uncertain submission state before POST; a process crash must not
    # silently cause another billable request for the same image on restart.
    def checkpoint(raw, metadata):
        if saved_meta:
            stored_metadata = dict(metadata)
            if raw is not None:
                # Store decompressed JSON where possible so credential redaction
                # also applies to gzip responses. Invalid bytes stay private.
                try:
                    raw = _decode_response(raw, metadata)
                    stored_metadata["body_encoding"] = "identity"
                except SeedreamError:
                    pass
                _private_write(saved_body, raw.replace(api_key.encode("ascii"), b"[API Key hidden]"))
            _private_write(saved_meta, json.dumps({**stored_metadata, "request_fingerprint": fingerprint}, ensure_ascii=False).encode())
    for attempt in range(3):
        _check_cancel(stop_event)
        if request_gate is not None and request_gate.acquire(stop_event) is False:
            raise SeedreamError("任务已取消，未发起新的 Seedream 请求。", code="Cancelled")
        _check_cancel(stop_event)
        metadata = {"complete": False, "response_bytes": 0, "content_encoding": "identity"}
        checkpoint(None, metadata)
        stage = "request_send"
        try:
            with urllib.request.urlopen(request, timeout=REQUEST_TIMEOUT, context=context) as response:
                metadata.update(_response_metadata(response, api_key))
                checkpoint(None, metadata)
                stage = "response_read"
                try:
                    raw = response.read(MAX_RESPONSE_BYTES + 1)
                except http.client.IncompleteRead as exc:
                    metadata["response_bytes"] = len(exc.partial)
                    checkpoint(exc.partial, metadata)
                    raise SeedreamError("Seedream 响应传输中断，未收到完整结果；已记录 Request ID，没有自动重新生成。", code="ResponseIncomplete", request_id=metadata.get("request_id"), diagnostic={"stage": stage, "exception_type": "IncompleteRead", "response_bytes": len(exc.partial)}) from None
            metadata.update(complete=True, response_bytes=len(raw))
            checkpoint(raw, metadata)
        except urllib.error.HTTPError as exc:
            # Only explicit client rejection permits another POST on a later run.
            # A 5xx result can leave generation status unknown.
            if saved_meta and exc.code in {400, 401, 403, 404, 422, 429}:
                saved_meta.unlink(missing_ok=True)
                saved_body.unlink(missing_ok=True)
            elif saved_meta:
                metadata.update(_response_metadata(exc, api_key))
                checkpoint(None, metadata)
            if exc.code == 429 and attempt < 2:
                delay = _retry_delay(exc.headers, attempt)
                exc.close()
                if on_retry:
                    on_retry(f"图片接口限流（HTTP 429），等待 {delay:.1f} 秒后重试（第 {attempt + 2}/3 次请求）。")
                _wait_for_retry(delay, stop_event)
                continue
            error = {}
            try:
                body = json.loads(exc.read(100_000))
                error = body.get("error", {}) if isinstance(body, dict) else {}
            except (ValueError, OSError, http.client.HTTPException):
                pass
            finally:
                exc.close()
            failure = _service_error(error, api_key, exc.code, request_id=_header_value(exc.headers, "X-Request-Id") or _header_value(exc.headers, "X-Tt-Logid"))
            failure.diagnostic = {"stage": stage, "exception_type": "HTTPError"}
            raise failure from None
        except SeedreamError:
            raise
        except (urllib.error.URLError, TimeoutError, OSError, http.client.HTTPException) as exc:
            checkpoint(None, metadata)
            raise SeedreamError("Seedream 连接失败或超时，生成状态未知；已保存本地记录，为避免重复收费，没有自动重发。", code="GenerationConnectionFailed", request_id=metadata.get("request_id"), diagnostic={"stage": stage, "exception_type": type(exc).__name__, "response_bytes": metadata.get("response_bytes", 0)}) from None
        except (ValueError, TypeError, AttributeError) as exc:
            raise SeedreamError("Seedream 请求发送或读取失败，已记录具体阶段；没有自动重新生成。", code="GenerationTransportError", request_id=metadata.get("request_id"), diagnostic={"stage": stage, "exception_type": type(exc).__name__}) from None
        return _parse_response(raw, metadata, api_key, size, context, on_retry)
